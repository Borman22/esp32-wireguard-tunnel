#pragma once

#include <stdint.h>
#include "config.h"

/*
 * proxy.h — TCP-прокси: пробрасывает порты из туннеля в локальную сеть за роутером.
 *
 * Зачем: вы открываете http://<туннельный адрес платы>:8080 и попадаете
 * на веб-интерфейс роутера (192.168.1.1:80); то же для SSH и других
 * TCP-протоколов. Прокси ничего не разбирает, он просто гоняет байты, поэтому
 * подходит любой TCP-протокол.
 *
 * Принимаются только соединения, адресованные туннельному IP платы: слушающие
 * сокеты открыты на всех интерфейсах (так они не зависят от пересоздания
 * туннельного интерфейса), но чужие подключения из локальной сети и из AP
 * отбрасываются сразу после accept().
 *
 * Всё работает в одной задаче на select(): сокетов мало, лишние задачи и их
 * стеки на ESP32-C3 дороже.
 *
 * Бюджет сокетов lwIP (CONFIG_LWIP_MAX_SOCKETS = 16, жёсткий максимум):
 *   httpd: 2 открытых + 3 служебных            = 5
 *   прокси: PROXY_MAX_RULES слушающих          = 3
 *           PROXY_MAX_CONNS пар (клиент+цель)  = 8
 *   итого                                      = 16
 */

#ifndef PROXY_HALF_CLOSE      /* 1 = передавать закрытие одной стороны через shutdown(SHUT_WR) */
#define PROXY_HALF_CLOSE           0   /* на железе выключено: см. комментарий в proxy.c (conn_service) */
#endif
#define PROXY_MAX_CONNS            4       /* одновременных проксируемых соединений */
#define PROXY_LISTEN_BACKLOG       8       /* очередь ожидающих соединений в lwIP, пока нет свободного слота */
#ifndef PROXY_BUF_SIZE
#if CONFIG_IDF_TARGET_ESP32S3
#define PROXY_BUF_SIZE             4096    /* буфер на одно направление одного соединения (S3: ОЗУ больше) */
#else
#define PROXY_BUF_SIZE             2048    /* то же для C3: ОЗУ меньше */
#endif
#endif
#define PROXY_CONNECT_TIMEOUT_S    10      /* ждать подключения к цели не дольше */
#define PROXY_IDLE_TIMEOUT_S       300     /* закрывать соединение без трафика через */
#ifndef PROXY_EVICT_IDLE_S   /* тест собирается с коротким значением */
/* при нехватке слотов вытесняется соединение, молчащее не меньше этого. Порог большой:
 * рукопожатие TLS у слабого роутера (TP-Link) занимает 1–3 с, а шесть параллельных идут по очереди,
 * поэтому короткий порог обрывал ещё не отвеченные соединения, и браузер переоткрывал их по кругу */
#define PROXY_EVICT_IDLE_S         15
#endif
#define PROXY_HALF_CLOSE_TIMEOUT_S 30      /* то же, если одна сторона уже закрылась: слотов всего три */

/** Статистика для страницы «Статус». */
typedef struct {
    uint32_t active_conns;     /* сейчас открытых соединений */
    uint32_t total_conns;      /* принято с момента старта */
    uint32_t rejected_conns;   /* отброшено (чужой адрес или нет свободного слота) */
    uint32_t failed_target;    /* не удалось подключиться к цели */
} proxy_stats_t;

/**
 * Запустить прокси. rules — массив из PROXY_MAX_RULES правил (пустые слоты с
 * listen_port == 0 пропускаются), tunnel_ip — туннельный адрес платы в виде
 * строки (из него определяется, какие соединения принимать).
 * Если нет ни одного правила или адрес пуст, задача не создаётся.
 */
void proxy_start(const proxy_rule_t *rules, const char *tunnel_ip);

void proxy_get_stats(proxy_stats_t *out);
